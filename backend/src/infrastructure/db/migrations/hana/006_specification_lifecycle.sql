CREATE TABLE project_specification_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id NVARCHAR(64) NOT NULL,
    version_number INTEGER NOT NULL,
    version_tag NVARCHAR(64) DEFAULT 'DRAFT' NOT NULL,
    status NVARCHAR(32) DEFAULT 'DRAFT' NOT NULL,
    snapshot NCLOB DEFAULT '{}' NOT NULL,
    changelog NCLOB,
    created_by NVARCHAR(128) DEFAULT 'Lead SAP Architect' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_UTCTIMESTAMP NOT NULL,
    FOREIGN KEY (project_id) REFERENCES generation_projects(project_id) ON DELETE CASCADE,
    CONSTRAINT uq_project_spec_version UNIQUE (project_id, version_number)
);

CREATE INDEX idx_spec_versions_project ON project_specification_versions(project_id);
CREATE INDEX idx_spec_versions_status ON project_specification_versions(status);

CREATE TABLE project_specification_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id NVARCHAR(64) NOT NULL,
    version_number INTEGER NOT NULL,
    decision NVARCHAR(32) NOT NULL,
    comments NCLOB,
    approver NVARCHAR(128) NOT NULL,
    approver_role NVARCHAR(64) DEFAULT 'CHIEF_ARCHITECT' NOT NULL,
    approved_at TIMESTAMP DEFAULT CURRENT_UTCTIMESTAMP NOT NULL,
    signature_hash NVARCHAR(128) NOT NULL,
    FOREIGN KEY (project_id) REFERENCES generation_projects(project_id) ON DELETE CASCADE
);

CREATE INDEX idx_spec_approvals_project ON project_specification_approvals(project_id);


CREATE TABLE security_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id NVARCHAR(64) NOT NULL,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    actor NVARCHAR(128) NOT NULL,
    tenant_id NVARCHAR(64) NOT NULL,
    action NVARCHAR(64) NOT NULL,
    resource NVARCHAR(255) NOT NULL,
    correlation_id NVARCHAR(128),
    outcome NVARCHAR(32) DEFAULT 'SUCCESS' NOT NULL,
    details NCLOB,
    previous_hash NVARCHAR(128) NOT NULL,
    integrity_hash NVARCHAR(128) NOT NULL,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE
);

CREATE TABLE token_revocations (
    token_hash NVARCHAR(128) PRIMARY KEY,
    tenant_id NVARCHAR(64) NOT NULL,
    user_id NVARCHAR(64) NOT NULL,
    revoked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    reason NVARCHAR(64) DEFAULT 'LOGOUT' NOT NULL,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE
);

CREATE TABLE refresh_tokens (
    token_hash NVARCHAR(128) PRIMARY KEY,
    family_id NVARCHAR(128) NOT NULL,
    tenant_id NVARCHAR(64) NOT NULL,
    user_id NVARCHAR(64) NOT NULL,
    email NVARCHAR(255) NOT NULL,
    role NVARCHAR(64) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    is_revoked BOOLEAN DEFAULT FALSE NOT NULL,
    used_at TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE
);

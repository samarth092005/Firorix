CREATE INDEX idx_deployment_plans_status ON deployment_plans(status);

CREATE TABLE deployment_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id NVARCHAR(64) NOT NULL,
    project_id NVARCHAR(64) NOT NULL,
    tenant_id NVARCHAR(64) DEFAULT 'DEFAULT-TENANT-S21' NOT NULL,
    decision NVARCHAR(32) NOT NULL,
    approver NVARCHAR(128) NOT NULL,
    approver_role NVARCHAR(64) DEFAULT 'CHIEF_ARCHITECT' NOT NULL,
    plan_hash NVARCHAR(128) NOT NULL,
    artifact_manifest_hash NVARCHAR(128) NOT NULL,
    signature_hash NVARCHAR(128) NOT NULL,
    approved_at TIMESTAMP DEFAULT CURRENT_UTCTIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    comments NCLOB,
    FOREIGN KEY (plan_id) REFERENCES deployment_plans(id) ON DELETE CASCADE
);

CREATE INDEX idx_deployment_approvals_plan ON deployment_approvals(plan_id);
CREATE INDEX idx_deployment_approvals_project ON deployment_approvals(project_id);


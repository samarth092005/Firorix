CREATE TABLE deployment_plans (
    id NVARCHAR(64) PRIMARY KEY,
    project_id NVARCHAR(64) NOT NULL,
    tenant_id NVARCHAR(64) DEFAULT 'DEFAULT-TENANT-S21' NOT NULL,
    target_system NVARCHAR(32) DEFAULT 'S21' NOT NULL,
    target_client NVARCHAR(8) DEFAULT '200' NOT NULL,
    target_package NVARCHAR(64) DEFAULT '$TMP' NOT NULL,
    target_namespace NVARCHAR(16) DEFAULT 'Z' NOT NULL,
    transport_request NVARCHAR(32),
    specification_version INTEGER DEFAULT 1 NOT NULL,
    generation_version INTEGER DEFAULT 1 NOT NULL,
    plan_hash NVARCHAR(128) NOT NULL,
    artifact_manifest_hash NVARCHAR(128) NOT NULL,
    status NVARCHAR(32) DEFAULT 'PLANNED' NOT NULL,
    plan_details NCLOB DEFAULT '{}' NOT NULL,
    created_by NVARCHAR(128) DEFAULT 'Lead SAP Architect' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_UTCTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_UTCTIMESTAMP NOT NULL,
    FOREIGN KEY (project_id) REFERENCES generation_projects(project_id) ON DELETE CASCADE
);

CREATE INDEX idx_deployment_plans_project ON deployment_plans(project_id);

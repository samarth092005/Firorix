-- SAP HANA Cloud Migration: 001_initial_schema.sql
-- Description: Core schema for Fiorify SAP Modernization Platform on SAP HANA Cloud
-- Deployment Target: SAP BTP Cloud Foundry / SAP HANA Cloud HDI Container

CREATE TABLE schema_migrations (
    version NVARCHAR(64) PRIMARY KEY,
    name NVARCHAR(255) NOT NULL,
    checksum NVARCHAR(128) NOT NULL,
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    execution_time_ms INTEGER NOT NULL
);

CREATE TABLE tenants (
    tenant_id NVARCHAR(64) PRIMARY KEY,
    name NVARCHAR(255) NOT NULL,
    status NVARCHAR(32) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE sap_system_profiles (
    id NVARCHAR(64) PRIMARY KEY,
    tenant_id NVARCHAR(64) NOT NULL,
    system_id NVARCHAR(16) NOT NULL,
    client NVARCHAR(8) NOT NULL,
    release NVARCHAR(64) DEFAULT 'SAP S/4HANA 2023 On-Premise' NOT NULL,
    description NVARCHAR(255),
    destination_name NVARCHAR(128),
    is_active BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_tenant_system_client UNIQUE (tenant_id, system_id, client),
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE
);

CREATE TABLE fiori_catalog_sources (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name NVARCHAR(128) NOT NULL,
    source_type NVARCHAR(64) NOT NULL,
    source_version NVARCHAR(128) NOT NULL,
    target_release NVARCHAR(64) DEFAULT 'SAP S/4HANA 2023 On-Premise' NOT NULL,
    record_count INTEGER DEFAULT 0 NOT NULL,
    content_hash NVARCHAR(128) NOT NULL,
    status NVARCHAR(32) DEFAULT 'SUCCESS' NOT NULL,
    summary NCLOB,
    imported_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE fiori_catalog_apps (
    app_id NVARCHAR(64) PRIMARY KEY,
    app_name NVARCHAR(255) NOT NULL,
    description NCLOB,
    app_type NVARCHAR(64) NOT NULL,
    ui_technology NVARCHAR(64) NOT NULL,
    business_process NCLOB,
    line_of_business NCLOB,
    product_version NVARCHAR(128),
    software_component NVARCHAR(128),
    business_role NCLOB,
    application_component NVARCHAR(128),
    leading_transaction NVARCHAR(64),
    odata_services NCLOB,
    business_catalog NVARCHAR(255),
    search_vector NCLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE transaction_profiles (
    tcode NVARCHAR(64) NOT NULL,
    tenant_id NVARCHAR(64) NOT NULL,
    system_id NVARCHAR(16) NOT NULL,
    description NVARCHAR(255) NOT NULL,
    program_name NVARCHAR(128) NOT NULL,
    screen_number NVARCHAR(16) DEFAULT '0100',
    package_name NVARCHAR(128) DEFAULT '$TMP',
    classification NVARCHAR(32) DEFAULT 'STANDARD' NOT NULL,
    software_component NVARCHAR(128),
    business_process NVARCHAR(128),
    business_sub_process NVARCHAR(128),
    dialog_steps_per_month INTEGER DEFAULT 0,
    active_users_count INTEGER DEFAULT 0,
    has_custom_modifications BOOLEAN DEFAULT FALSE,
    clean_core_tier NVARCHAR(32) DEFAULT 'TIER_1_STANDARD',
    raw_metadata NCLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (tcode, tenant_id, system_id),
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE
);

CREATE TABLE assessments (
    id NVARCHAR(64) PRIMARY KEY,
    tenant_id NVARCHAR(64) NOT NULL,
    tcode NVARCHAR(64) NOT NULL,
    candidate_app_id NVARCHAR(64),
    candidate_app_name NVARCHAR(255),
    status NVARCHAR(64) NOT NULL,
    lifecycle_status NVARCHAR(64) DEFAULT 'DRAFT' NOT NULL,
    fit_gap_score DECIMAL(5, 2) DEFAULT 0.00 NOT NULL,
    confidence_level NVARCHAR(32) DEFAULT 'MEDIUM' NOT NULL,
    dimension_scores NCLOB NOT NULL,
    gap_summary NCLOB,
    recommendation NCLOB NOT NULL,
    evidence_bundle NCLOB,
    lead_architect_approval NCLOB,
    version INTEGER DEFAULT 1 NOT NULL,
    is_archived BOOLEAN DEFAULT FALSE NOT NULL,
    created_by NVARCHAR(64) NOT NULL,
    updated_by NVARCHAR(64),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE
);

CREATE TABLE assessment_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id NVARCHAR(64) NOT NULL,
    tenant_id NVARCHAR(64) NOT NULL,
    event_id NVARCHAR(64) NOT NULL,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    author NVARCHAR(255) NOT NULL,
    actor_id NVARCHAR(64) NOT NULL,
    actor_role NVARCHAR(64) NOT NULL,
    previous_state NVARCHAR(64) NOT NULL,
    new_state NVARCHAR(64) NOT NULL,
    action NVARCHAR(64) NOT NULL,
    comment NCLOB,
    details NCLOB,
    previous_hash NVARCHAR(128) NOT NULL,
    integrity_hash NVARCHAR(128) NOT NULL,
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE
);
